defmodule Atlas.Storage.LocalDisk do
  @moduledoc """
  Development and test adapter. Files live under the configured `:root`.

  Signed URLs point at `AtlasWeb.ImageController`, which checks the signature and expiry
  the same way an R2 presigned URL is checked by R2.
  """
  @behaviour Atlas.Storage

  @salt "storage-url"

  @impl true
  def put(key, body, _content_type) do
    path = path(key)

    with :ok <- File.mkdir_p(Path.dirname(path)) do
      File.write(path, body)
    end
  end

  @impl true
  def delete(key) do
    case File.rm(path(key)) do
      :ok -> :ok
      {:error, :enoent} -> :ok
      {:error, reason} -> {:error, reason}
    end
  end

  @impl true
  def signed_url(key, _ttl_seconds) do
    "/api/images/" <> Phoenix.Token.sign(AtlasWeb.Endpoint, @salt, key)
  end

  @doc "Resolves a signed token to file contents, or `:error` when it is invalid or expired."
  def read_signed(token) do
    with {:ok, key} <-
           Phoenix.Token.verify(AtlasWeb.Endpoint, @salt, token,
             max_age: Atlas.Storage.ttl_seconds()
           ),
         {:ok, body} <- File.read(path(key)) do
      {:ok, body}
    else
      _ -> :error
    end
  end

  defp path(key) do
    root =
      :atlas |> Application.fetch_env!(Atlas.Storage) |> Keyword.fetch!(:root) |> Path.expand()

    # Keys are generated by the server; this guards against a bug, not against clients.
    case Path.safe_relative(key, root) do
      {:ok, relative} -> Path.join(root, relative)
      :error -> raise ArgumentError, "unsafe storage key"
    end
  end
end
